package net.xfbs.pdfrs

import android.content.Intent
import android.net.Uri
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.test.assertIsDisplayed
import androidx.compose.ui.test.click
import androidx.compose.ui.test.junit4.v2.createEmptyComposeRule
import androidx.compose.ui.test.onAllNodesWithContentDescription
import androidx.compose.ui.test.onAllNodesWithTag
import androidx.compose.ui.test.onAllNodesWithText
import androidx.compose.ui.test.onNodeWithContentDescription
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.performTextInput
import androidx.compose.ui.test.performTouchInput
import androidx.compose.ui.test.swipeLeft
import androidx.compose.ui.test.swipeRight
import androidx.test.core.app.ActivityScenario
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import org.junit.After
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Smoke tests of the reader, each starting from a freshly opened document.
 * They run on phones and tablets alike; where the two differ (a wide window
 * shows Pages beside the document instead of full screen), tests ask [wide]. The page itself is drawn on a canvas and invisible
 * to tests, so they look at what surrounds it: the page indicator and bars.
 *
 * Run on an emulator with
 * `ANDROID_SERIAL=emulator-5554 ./gradlew :app:connectedDebugAndroidTest`
 * (the serial picks the emulator, and keeps the tests off a phone that
 * happens to be plugged in: the run reinstalls the app). The documents are in `src/androidTest/assets`,
 * generated by `make-fixtures.py`.
 */
@RunWith(AndroidJUnit4::class)
class ReaderTest {
    @get:Rule
    val compose = createEmptyComposeRule()

    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private var scenario: ActivityScenario<MainActivity>? = null

    /** Whether the window is wide enough for the sidebar layout. */
    private val wide: Boolean
        get() = instrumentation.targetContext.resources.configuration.screenWidthDp >= WIDE_WINDOW_DP

    @Before
    fun forgetEverything() {
        // No reading positions or recents from earlier tests.
        File(instrumentation.targetContext.filesDir, "documents.json").delete()
    }

    @After
    fun close() {
        scenario?.close()
    }

    /** Opens a document from the test assets the way another app would hand it over. */
    private fun open(asset: String) {
        val target = instrumentation.targetContext
        val file = File(target.cacheDir, asset)
        instrumentation.context.assets.open(asset).use { input ->
            file.outputStream().use { input.copyTo(it) }
        }
        scenario?.close()
        scenario = ActivityScenario.launch(
            Intent(target, MainActivity::class.java)
                .setAction(Intent.ACTION_VIEW)
                .setDataAndType(Uri.fromFile(file), "application/pdf"),
        )
        waitForText("1 / 12")
    }

    private fun waitForText(text: String) {
        compose.waitUntil(10_000) { compose.onAllNodesWithText(text).fetchSemanticsNodes().isNotEmpty() }
    }

    private fun waitUntilGone(text: String) {
        compose.waitUntil(10_000) { compose.onAllNodesWithText(text).fetchSemanticsNodes().isEmpty() }
    }

    private val page get() = compose.onNodeWithTag(PAGE_VIEW_TAG)

    @Test
    fun opensOnTheFirstPage() {
        open("pages.pdf")
        compose.onNodeWithText("pages.pdf").assertIsDisplayed()
        compose.onNodeWithText("1 / 12").assertIsDisplayed()
    }

    @Test
    fun swipingTurnsOnePage() {
        open("pages.pdf")
        page.performTouchInput { swipeLeft() }
        waitForText("2 / 12")
        page.performTouchInput { swipeLeft() }
        waitForText("3 / 12")
        page.performTouchInput { swipeRight() }
        waitForText("2 / 12")
    }

    @Test
    fun aShortSlowDragReturnsToThePage() {
        open("pages.pdf")
        page.performTouchInput {
            down(center)
            // A quarter of the width, slowly, then held still: no flick.
            repeat(10) { moveBy(Offset(-width / 40f, 0f), delayMillis = 50) }
            advanceEventTime(300)
            up()
        }
        compose.waitForIdle()
        compose.onNodeWithText("1 / 12").assertIsDisplayed()
    }

    @Test
    fun aShortFlickTurnsThePage() {
        open("pages.pdf")
        page.performTouchInput {
            down(center)
            // The same quarter of the width, but fast and released in motion.
            repeat(5) { moveBy(Offset(-width / 20f, 0f), delayMillis = 8) }
            up()
        }
        waitForText("2 / 12")
    }

    @Test
    fun thePageGridJumpsToAPage() {
        open("pages.pdf")
        // Already there beside the document on a wide window.
        if (!wide) compose.onNodeWithContentDescription("Contents and pages").performClick()
        waitForText("7")
        compose.onNodeWithText("7").performClick()
        waitForText("7 / 12")
    }

    @Test
    fun goToPageFromTheMenu() {
        open("pages.pdf")
        compose.onNodeWithContentDescription("More").performClick()
        compose.onNodeWithText("Go to page…").performClick()
        compose.onNodeWithText("Page (1–12)").performTextInput("9")
        compose.onNodeWithText("Go").performClick()
        waitForText("9 / 12")
    }

    @Test
    fun aTapTogglesFullScreen() {
        open("pages.pdf")
        page.performTouchInput { click(center) }
        // The bars and the page indicator leave ...
        waitUntilGone("pages.pdf")
        waitUntilGone("1 / 12")
        compose.waitUntil(10_000) {
            compose.onAllNodesWithContentDescription("More").fetchSemanticsNodes().isEmpty() &&
                compose.onAllNodesWithTag(SIDEBAR_TAG).fetchSemanticsNodes().isEmpty()
        }
        // ... and another tap brings them back.
        page.performTouchInput { click(center) }
        waitForText("pages.pdf")
        waitForText("1 / 12")
    }

    @Test
    fun aWideWindowShowsPagesBesideTheDocument() {
        assumeTrue("needs a window of at least $WIDE_WINDOW_DP dp", wide)
        open("pages.pdf")
        // Both at once, and without the thumbnail strip's job being done twice.
        compose.onNodeWithTag(SIDEBAR_TAG).assertIsDisplayed()
        page.assertIsDisplayed()
        val sidebarWidth = compose.onNodeWithTag(SIDEBAR_TAG).fetchSemanticsNode().size.width
        val pageWidth = page.fetchSemanticsNode().size.width
        assertTrue("the document gets most of the width", pageWidth > 2 * sidebarWidth)

        // Picking a page keeps the sidebar; the button folds it away, and the
        // document takes the room.
        compose.onNodeWithText("5").performClick()
        waitForText("5 / 12")
        compose.onNodeWithTag(SIDEBAR_TAG).assertIsDisplayed()
        compose.onNodeWithContentDescription("Contents and pages").performClick()
        compose.waitUntil(10_000) { compose.onAllNodesWithTag(SIDEBAR_TAG).fetchSemanticsNodes().isEmpty() }
        compose.waitForIdle()
        assertTrue(page.fetchSemanticsNode().size.width > pageWidth)
        compose.onNodeWithText("5 / 12").assertIsDisplayed()
    }

    @Test
    fun aNarrowWindowShowsPagesFullScreen() {
        assumeTrue("needs a window narrower than $WIDE_WINDOW_DP dp", !wide)
        open("pages.pdf")
        compose.onNodeWithContentDescription("Contents and pages").performClick()
        waitForText("7")
        // In place of the document, until a page is picked or Back is pressed.
        compose.onNodeWithTag(PAGE_VIEW_TAG).assertDoesNotExist()
        compose.onNodeWithContentDescription("Back to document").performClick()
        waitForText("1 / 12")
        page.assertIsDisplayed()
    }

    @Test
    fun reopeningContinuesWhereTheReaderLeftOff() {
        open("pages.pdf")
        page.performTouchInput { swipeLeft() }
        waitForText("2 / 12")
        page.performTouchInput { swipeLeft() }
        waitForText("3 / 12")
        // Leaving saves the position; the same file opens there again.
        scenario?.close()
        scenario = null
        val target = instrumentation.targetContext
        scenario = ActivityScenario.launch(
            Intent(target, MainActivity::class.java)
                .setAction(Intent.ACTION_VIEW)
                .setDataAndType(Uri.fromFile(File(target.cacheDir, "pages.pdf")), "application/pdf"),
        )
        waitForText("3 / 12")
    }
}
